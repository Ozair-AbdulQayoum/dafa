// =========================================================
// NORMALIZE NAME
// =========================================================

export const normalizeProvinceName = (name = "") => {
  return name
    .toString()
    .toLowerCase()
    .trim()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[’'`]/g, "")
    .replace(/province/g, "")
    .replace(/wilayat/g, "")
    .replace(/ ولایت/g, "")
    .replace(/[-_]/g, " ")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
};

// =========================================================
// COMPACT NAME
// =========================================================

const compactProvinceName = (name = "") => {
  return normalizeProvinceName(name).replace(/\s+/g, "");
};

